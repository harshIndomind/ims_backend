/**
 * Reusable Charge + Tax calculation engine, shared by Purchase Order and Work
 * Order (and any future document — Purchase Invoice, Sales Invoice, etc. —
 * that needs the same item-tax + generic-charge math).
 *
 * A "charge" is a generic, configurable line (contingency, freight, packing,
 * insurance, a discount, TCS, ...) rather than a hardcoded named field:
 *
 *   { name, calculationType: 'FIXED'|'PERCENTAGE', value, operation: '+'|'-',
 *     applyOn: 'NET_TAXABLE_AMOUNT'|'AFTER_TAX',
 *     taxTreatment: 'NON_TAXABLE'|'SPECIFIC_RATE'|'INHERIT_ITEM_TAX', taxRate? }
 *
 * `applyOn` is purely an ordering/base concept (pre-tax vs post-tax);
 * `taxTreatment` is purely a tax-behavior concept — they are independent, per
 * the calculation engine design doc these functions implement.
 *
 * Percentage charges are always computed against a fixed base (the items-only
 * net taxable amount for pre-tax charges, the post-tax gross for post-tax
 * charges) — never cascaded through other charges — so behavior is
 * deterministic regardless of how many charges exist or what order they're
 * listed in.
 */

const { round2, sum } = require('./money');

const CALCULATION_TYPE = { FIXED: 'FIXED', PERCENTAGE: 'PERCENTAGE' };
const APPLY_ON = { NET_TAXABLE_AMOUNT: 'NET_TAXABLE_AMOUNT', AFTER_TAX: 'AFTER_TAX' };
const TAX_TREATMENT = {
	NON_TAXABLE: 'NON_TAXABLE',
	SPECIFIC_RATE: 'SPECIFIC_RATE',
	INHERIT_ITEM_TAX: 'INHERIT_ITEM_TAX',
};
const OPERATION = { ADD: '+', SUBTRACT: '-' };

/** Splits a tax amount into CGST+SGST (halves, second half absorbs rounding) or IGST. */
function splitTax(tax, sameState) {
	const amount = round2(tax);
	if (!amount) return { cgst: 0, sgst: 0, igst: 0 };
	if (sameState) {
		const cgst = round2(amount / 2);
		return { cgst, sgst: round2(amount - cgst), igst: 0 };
	}
	return { cgst: 0, sgst: 0, igst: amount };
}

/**
 * Per-item taxable amount + tax split. Mirrors the existing PO/WO
 * `calculateProductTotals` formula exactly (qty*price, then subtract
 * percentage/rupee discount, then tax on the discounted taxable amount).
 */
function calculateItemTax(item, sameState) {
	const qty = parseFloat(item.qty) || 0;
	const price = parseFloat(item.price) || 0;
	const discount = parseFloat(item.discount) || 0;
	const rate = parseFloat(item.rate) || 0;
	const cess = round2(parseFloat(item.cess) || 0);

	let subtotal = qty * price;
	if (item.discountType === 'percentage') {
		subtotal -= (subtotal * discount) / 100;
	} else if (item.discountType === 'rupee') {
		subtotal -= discount;
	}

	const taxableAmount = round2(subtotal);
	const taxAmount = round2((taxableAmount * rate) / 100);
	const { cgst, sgst, igst } = splitTax(taxAmount, sameState);
	const total = round2(taxableAmount + taxAmount + cess);

	return { taxableAmount, rate, taxAmount, cgst, sgst, igst, cess, total };
}

/** Fixed or percentage-of-base amount, signed by operation. */
function computeChargeAmount(charge, base) {
	const value = parseFloat(charge.value) || 0;
	const raw = charge.calculationType === CALCULATION_TYPE.PERCENTAGE ? (base * value) / 100 : value;
	const signed = charge.operation === OPERATION.SUBTRACT ? -raw : raw;
	return round2(signed);
}

/**
 * Tax generated by one charge amount, per its taxTreatment.
 * - NON_TAXABLE: zero tax.
 * - SPECIFIC_RATE: taxed at the charge's own configured rate.
 * - INHERIT_ITEM_TAX: proportionally allocated across the item tax buckets
 *   (never the highest/average/first-item rate), each slice taxed at its own
 *   bucket's rate — falls back to NON_TAXABLE only when there is nothing to
 *   allocate against (no items / zero taxable amount).
 */
function computeChargeTax(charge, amount, sameState, itemBuckets, netTaxableAmount) {
	if (charge.taxTreatment === TAX_TREATMENT.SPECIFIC_RATE) {
		const rate = parseFloat(charge.taxRate) || 0;
		const tax = round2((amount * rate) / 100);
		return { tax, ...splitTax(tax, sameState), appliedTaxTreatment: TAX_TREATMENT.SPECIFIC_RATE };
	}

	if (charge.taxTreatment === TAX_TREATMENT.INHERIT_ITEM_TAX) {
		if (!netTaxableAmount || itemBuckets.length === 0) {
			return { tax: 0, cgst: 0, sgst: 0, igst: 0, appliedTaxTreatment: TAX_TREATMENT.NON_TAXABLE, fellBackFrom: TAX_TREATMENT.INHERIT_ITEM_TAX };
		}
		let tax = 0;
		const allocation = itemBuckets.map(({ rate, taxableAmount }) => {
			const share = taxableAmount / netTaxableAmount;
			const slice = round2(amount * share);
			const sliceTax = round2((slice * rate) / 100);
			tax = round2(tax + sliceTax);
			return { rate, taxableAmount: slice, tax: sliceTax };
		});
		return { tax, ...splitTax(tax, sameState), appliedTaxTreatment: TAX_TREATMENT.INHERIT_ITEM_TAX, allocation };
	}

	return { tax: 0, cgst: 0, sgst: 0, igst: 0, appliedTaxTreatment: TAX_TREATMENT.NON_TAXABLE };
}

/** Runs one phase (pre-tax or post-tax) of charges against a fixed base. */
function processChargePhase(charges, base, sameState, itemBuckets, netTaxableAmount) {
	let amountTotal = 0;
	let taxTotal = 0;
	let cgstTotal = 0;
	let sgstTotal = 0;
	let igstTotal = 0;

	const breakdown = charges.map((charge) => {
		const amount = computeChargeAmount(charge, base);
		const taxResult = computeChargeTax(charge, amount, sameState, itemBuckets, netTaxableAmount);
		amountTotal = round2(amountTotal + amount);
		taxTotal = round2(taxTotal + taxResult.tax);
		cgstTotal = round2(cgstTotal + taxResult.cgst);
		sgstTotal = round2(sgstTotal + taxResult.sgst);
		igstTotal = round2(igstTotal + taxResult.igst);
		return {
			...charge,
			amount,
			tax: taxResult.tax,
			cgst: taxResult.cgst,
			sgst: taxResult.sgst,
			igst: taxResult.igst,
			appliedTaxTreatment: taxResult.appliedTaxTreatment,
		};
	});

	return { breakdown, amountTotal, taxTotal, cgstTotal, sgstTotal, igstTotal };
}

/**
 * The one entry point: items + charges + same_state (+ optional round-off) in,
 * a full deterministic breakdown out. Backend services should treat this
 * function's output as the authoritative persisted totals rather than
 * trusting client-sent totals.
 *
 * @param {{qty, price, discount, discountType: 'percentage'|'rupee', rate, cess}[]} items
 * @param {Charge[]} charges
 * @param {boolean} sameState
 * @param {boolean} [roundOff]
 */
function calculateDocumentTotals({ items = [], charges = [], sameState, roundOff = false }) {
	const itemResults = items.map((item) => calculateItemTax(item, sameState));

	const netTaxableAmount = round2(sum(itemResults.map((r) => r.taxableAmount)));
	const itemTaxTotal = round2(sum(itemResults.map((r) => r.taxAmount)));
	const itemCgst = round2(sum(itemResults.map((r) => r.cgst)));
	const itemSgst = round2(sum(itemResults.map((r) => r.sgst)));
	const itemIgst = round2(sum(itemResults.map((r) => r.igst)));
	const itemCess = round2(sum(itemResults.map((r) => r.cess)));

	// Item tax buckets keyed by rate — the fixed reference used by every
	// INHERIT_ITEM_TAX allocation, snapshotted before any charge is applied.
	const bucketMap = new Map();
	itemResults.forEach((r) => {
		bucketMap.set(r.rate, round2((bucketMap.get(r.rate) || 0) + r.taxableAmount));
	});
	const itemBuckets = Array.from(bucketMap.entries()).map(([rate, taxableAmount]) => ({ rate, taxableAmount }));

	const preTaxCharges = charges.filter((c) => c.applyOn === APPLY_ON.NET_TAXABLE_AMOUNT);
	const postTaxCharges = charges.filter((c) => c.applyOn === APPLY_ON.AFTER_TAX);

	const preTaxResult = processChargePhase(preTaxCharges, netTaxableAmount, sameState, itemBuckets, netTaxableAmount);

	// Fixes an existing bug: today's PO document-level total_taxable is
	// gross-of-discount (Σ qty*price); this is post-discount, consistent with
	// the item-level math it's derived from.
	const totalTaxable = round2(netTaxableAmount + preTaxResult.amountTotal);
	const taxAfterPreTaxCharges = round2(itemTaxTotal + preTaxResult.taxTotal);
	const grossAmount = round2(totalTaxable + taxAfterPreTaxCharges + itemCess);

	const postTaxResult = processChargePhase(postTaxCharges, grossAmount, sameState, itemBuckets, netTaxableAmount);

	const grandTotalBeforeRound = round2(grossAmount + postTaxResult.amountTotal + postTaxResult.taxTotal);

	let grandTotal;
	let roundOffAmount;
	if (roundOff) {
		grandTotal = Math.round(grandTotalBeforeRound);
		roundOffAmount = round2(grandTotal - grandTotalBeforeRound);
	} else {
		grandTotal = round2(grandTotalBeforeRound);
		roundOffAmount = 0;
	}

	return {
		items: itemResults,
		preTaxCharges: preTaxResult.breakdown,
		postTaxCharges: postTaxResult.breakdown,
		totalTaxable,
		totalTax: round2(taxAfterPreTaxCharges + postTaxResult.taxTotal),
		cgst: round2(itemCgst + preTaxResult.cgstTotal + postTaxResult.cgstTotal),
		sgst: round2(itemSgst + preTaxResult.sgstTotal + postTaxResult.sgstTotal),
		igst: round2(itemIgst + preTaxResult.igstTotal + postTaxResult.igstTotal),
		cess: itemCess,
		grossAmount,
		roundOffAmount,
		grandTotal,
	};
}

/**
 * Adapts a legacy PO/WO `customFields` [slot1, slot2] pair (the only "charge"
 * concept that existed before this engine) into the generic Charge shape, so
 * editing/viewing a pre-existing document reconstructs equivalent charges
 * instead of silently losing them. Legacy customFields were always post-tax,
 * non-taxable, free-text-named — a strict subset of the generic model.
 */
function legacyCustomFieldsToCharges(customFields) {
	return (customFields || [])
		.filter(Boolean)
		.filter((field) => field.amount != null && field.amount !== '')
		.map((field, index) => ({
			name: field.name || `Charge ${index + 1}`,
			calculationType: field.valueType === 'percentage' ? CALCULATION_TYPE.PERCENTAGE : CALCULATION_TYPE.FIXED,
			value: parseFloat(field.amount) || 0,
			operation: field.operationType === '-' ? OPERATION.SUBTRACT : OPERATION.ADD,
			applyOn: APPLY_ON.AFTER_TAX,
			taxTreatment: TAX_TREATMENT.NON_TAXABLE,
			sequence: index + 1,
		}));
}

module.exports = {
	CALCULATION_TYPE,
	APPLY_ON,
	TAX_TREATMENT,
	OPERATION,
	splitTax,
	calculateItemTax,
	computeChargeAmount,
	computeChargeTax,
	calculateDocumentTotals,
	legacyCustomFieldsToCharges,
};
