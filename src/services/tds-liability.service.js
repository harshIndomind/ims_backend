const { TdsLiability, PurchaseOrder, WorkOrder } = require('../models/index');
const tdsLiabilityRepo = require('../repository/tds-liability.repository');
const deductionRepo = require('../repository/payment-requisition-deduction.repository');
const auditLogService = require('./auditLog.service');
const AppError = require('../utils/AppError');
const { StatusCodes } = require('http-status-codes');
const logger = require('../utils/logger');
const money = require('../utils/money');
const { getTaxableRatio } = require('../utils/taxable-ratio.util');

const TDS_DEDUCTION_TYPES = ['TDS', 'GST_TDS', 'WCT'];

// Kept in sync with the identically-named constant in payment-requisition.service.js —
// see that file's comment for why WCT is excluded.
const TAXABLE_BASE_DEDUCTION_TYPES = ['TDS', 'GST_TDS'];

/**
 * Creates one TdsLiability per TDS-type deduction line on a requisition that
 * doesn't already have one. Called when a PaymentRequisition transitions into
 * APPROVED. Idempotent: the unique FK on payment_requisition_deduction_id
 * means a reject-then-re-approve cycle (or a retried request) can never
 * double-create a liability for the same deduction line.
 */
exports.createLiabilitiesForApprovedRequisition = async (req, requisition, transaction) => {
	const deductions = await deductionRepo.findByRequisitionId(requisition.id, { transaction });
	const tdsDeductions = deductions.filter((d) => TDS_DEDUCTION_TYPES.includes(d.deduction_type) && parseFloat(d.amount) > 0);

	if (tdsDeductions.length === 0) return [];

	// TDS/GST_TDS liabilities record the taxable (pre-GST) slice as base_amount —
	// matching the actual base the deduction amount was computed on (see
	// TAXABLE_BASE_DEDUCTION_TYPES in payment-requisition.service.js) — since
	// that's the figure that belongs in TDS return/audit reporting, not the
	// GST-inclusive gross. WCT keeps base_amount = gross_amount.
	const gross = parseFloat(requisition.gross_amount) || 0;
	let taxableRatio = 1;
	if (tdsDeductions.some((d) => TAXABLE_BASE_DEDUCTION_TYPES.includes(d.deduction_type))) {
		taxableRatio = await getTaxableRatio({
			PurchaseOrder,
			WorkOrder,
			po_id: requisition.po_id,
			wo_id: requisition.wo_id,
			transaction,
		});
	}
	const taxableBase = money.round2(gross * taxableRatio);

	const created = [];
	for (const deduction of tdsDeductions) {
		const existing = await tdsLiabilityRepo.findByDeductionId(deduction.id, { transaction });
		if (existing) continue;

		const baseAmount = TAXABLE_BASE_DEDUCTION_TYPES.includes(deduction.deduction_type) ? taxableBase : gross;

		const liability = await tdsLiabilityRepo.create(
			{
				org_id: requisition.org_id,
				source_type: requisition.po_id ? 'PO' : 'WO',
				po_id: requisition.po_id || null,
				wo_id: requisition.wo_id || null,
				payment_requisition_id: requisition.id,
				payment_requisition_deduction_id: deduction.id,
				vendor_id: requisition.supplier_id || null,
				vendor_snapshot: requisition.supplier_snapshot || null,
				deduction_type: deduction.deduction_type,
				base_amount: baseAmount,
				tds_percentage: deduction.percentage,
				tds_amount: parseFloat(deduction.amount) || 0,
				amount_settled: 0,
				status: 'UNPAID',
				liability_date: requisition.payment_date || requisition.requisition_date,
				created_by_id: req.user.id,
			},
			{ transaction },
		);

		await auditLogService.record({
			req,
			entityType: 'tds_liability',
			entityId: liability.id,
			action: 'create',
			newState: { payment_requisition_id: requisition.id, deduction_type: deduction.deduction_type, tds_amount: deduction.amount },
			transaction,
		});

		created.push(liability);
	}

	logger.info('TDS liabilities created for approved requisition', { requisitionId: requisition.id, count: created.length });
	return created;
};

/**
 * Cancels every non-settled TdsLiability generated by a requisition that is
 * being reversed (APPROVED -> REJECTED, or deleted after approval). Blocks the
 * reversal if any liability already has settlement applied — that must be
 * reversed via the settlement /reverse endpoint first, since the money has
 * already left the org's account.
 */
exports.cancelLiabilitiesForRequisition = async (req, requisitionId, reason, transaction) => {
	const liabilities = await TdsLiability.findAll({
		where: { payment_requisition_id: requisitionId, status: { [require('sequelize').Op.ne]: 'CANCELLED' } },
		transaction,
		lock: transaction.LOCK.UPDATE,
	});

	const settled = liabilities.filter((l) => parseFloat(l.amount_settled) > 0);
	if (settled.length > 0) {
		throw new AppError(
			'Cannot reverse this requisition: one or more TDS liabilities it generated have already been settled with the government. Reverse the settlement first.',
			StatusCodes.CONFLICT,
		);
	}

	for (const liability of liabilities) {
		await liability.update(
			{
				status: 'CANCELLED',
				cancelled_at: new Date(),
				cancelled_by_id: req.user.id,
				cancellation_reason: reason || null,
			},
			{ transaction },
		);

		await auditLogService.record({
			req,
			entityType: 'tds_liability',
			entityId: liability.id,
			action: 'cancel',
			previousState: { status: 'UNPAID' },
			newState: { status: 'CANCELLED', reason },
			transaction,
		});
	}

	return liabilities;
};

exports.getAllTdsLiabilities = async (req) => {
	const { org_id } = req.user;
	const { fromDate, toDate, po_id, wo_id, vendor_id, status, payment_requisition_id, limit, offset } = req.query;
	const where = tdsLiabilityRepo.buildFilterWhere({ org_id, fromDate, toDate, po_id, wo_id, vendor_id, status, payment_requisition_id });
	return tdsLiabilityRepo.findAll(where, { limit, offset });
};

exports.getTdsLiabilityById = async (req, id) => {
	const { org_id } = req.user;
	const liability = await tdsLiabilityRepo.findById(id);
	if (!liability || liability.org_id !== org_id) {
		throw new AppError('TDS liability not found', StatusCodes.NOT_FOUND);
	}
	return liability;
};

exports.getTdsSummary = async (req) => {
	const { org_id } = req.user;
	const { fromDate, toDate } = req.query;
	const summary = await tdsLiabilityRepo.getSummary({ org_id, fromDate, toDate });
	return {
		liabilityCount: parseInt(summary?.liability_count || 0),
		totalLiability: parseFloat(summary?.total_liability || 0),
		totalPaid: parseFloat(summary?.total_paid || 0),
		totalOutstanding: parseFloat(summary?.total_outstanding || 0),
	};
};
